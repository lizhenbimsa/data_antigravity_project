# ============================================================================
# 文本归一化
# ============================================================================

def _normalize_text(text: str) -> str:
    """统一全角→半角、大小写，去除多余空白。"""
    # 全角→半角
    result = []
    for ch in text:
        code = ord(ch)
        # 全角空格
        if code == 0x3000:
            result.append(' ')
        # 全角 ASCII 字符 (！→~)
        elif 0xFF01 <= code <= 0xFF5E:
            result.append(chr(code - 0xFEE0))
        else:
            result.append(ch)
    normalized = ''.join(result)
    # 大写统一
    normalized = normalized.upper()
    # 去除多余空白
    normalized = ' '.join(normalized.split())
    return normalized


