# 预构建归一化后的关键词查找表
_TECH_NORMALIZED = [(kw.upper(), weight, sub) for kw, weight, sub in TECHNOLOGY_KEYWORDS]
_APP_NORMALIZED  = [(kw.upper(), weight, sub) for kw, weight, sub in APPLICATION_KEYWORDS]


def canonicalize_topic(raw_topic: str) -> tuple:
    """将 LLM 输出的 fintech_topic 标准化为「底层技术」或「应用场景」。

    增强版：支持加权评分、子类别标签和分类置信度。

    Args:
        raw_topic: LLM 返回的自由文本主题描述

    Returns:
        tuple: (category, subcategory, confidence)
            - category: "底层技术" 或 "应用场景"
            - subcategory: 匹配到的子类别（如"人工智能"、"智能风控"），
                           未匹配到时为 "未分类"
            - confidence: 0.0~1.0 之间的分类置信度
    """
    if not raw_topic or raw_topic.strip().lower() in ('null', 'none', ''):
        return ("应用场景", "未分类", 0.0)

    text = _normalize_text(raw_topic)

    # 第一轮：加权关键词匹配
    tech_score = 0.0
    app_score = 0.0
    tech_subcategories: dict[str, float] = {}
    app_subcategories: dict[str, float] = {}

    for kw, weight, sub in _TECH_NORMALIZED:
        if kw in text:
            tech_score += weight
            tech_subcategories[sub] = tech_subcategories.get(sub, 0.0) + weight

    for kw, weight, sub in _APP_NORMALIZED:
        if kw in text:
            app_score += weight
            app_subcategories[sub] = app_subcategories.get(sub, 0.0) + weight

    total_score = tech_score + app_score

    if total_score > 0:
        if tech_score > app_score:
            best_sub = max(tech_subcategories, key=tech_subcategories.get)
            confidence = min(tech_score / max(total_score, 1.0), 1.0)
            return ("底层技术", best_sub, round(confidence, 3))
        else:
            best_sub = max(app_subcategories, key=app_subcategories.get)
            confidence = min(app_score / max(total_score, 1.0), 1.0)
            return ("应用场景", best_sub, round(confidence, 3))

    # 第二轮：模糊匹配
    try:
        from fuzzywuzzy import fuzz

        best_tech_match = ("", 0, "未分类")
        for kw, weight, sub in _TECH_NORMALIZED:
            score = fuzz.partial_token_set_ratio(text, kw)
            if score > best_tech_match[1]:
                best_tech_match = (kw, score, sub)

        best_app_match = ("", 0, "未分类")
        for kw, weight, sub in _APP_NORMALIZED:
            score = fuzz.partial_token_set_ratio(text, kw)
            if score > best_app_match[1]:
                best_app_match = (kw, score, sub)

        if best_tech_match[1] > best_app_match[1] and best_tech_match[1] >= 60:
            confidence = best_tech_match[1] / 100.0 * 0.7  # 模糊匹配置信度打折
            return ("底层技术", best_tech_match[2], round(confidence, 3))
        elif best_app_match[1] >= 60:
            confidence = best_app_match[1] / 100.0 * 0.7
            return ("应用场景", best_app_match[2], round(confidence, 3))
    except ImportError:
        logger.warning("fuzzywuzzy 未安装，跳过模糊匹配")

    # 兜底：默认归为应用场景
    return ("应用场景", "未分类", 0.0)
